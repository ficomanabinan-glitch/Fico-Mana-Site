export type WebsiteCopyKey = typeof WEBSITE_COPY_SECTIONS[number]['fields'][number]['key']
export type WebsiteCopy = Record<WebsiteCopyKey, string>
export const WEBSITE_COPY_FIELDS = WEBSITE_COPY_SECTIONS.flatMap(section => [...section.fields])
export const DEFAULT_WEBSITE_COPY = Object.fromEntries(WEBSITE_COPY_FIELDS.map(field => [field.key, field.defaultValue])) as WebsiteCopy

export function mapWebsiteCopy(value: unknown): WebsiteCopy {
  const source = value && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : {}
  return Object.fromEntries(WEBSITE_COPY_FIELDS.map(field => [field.key,
    typeof source[field.key] === 'string' && (source[field.key] as string).trim()
      ? (source[field.key] as string).slice(0, field.maxLength)
      : field.defaultValue,
  ])) as WebsiteCopy
}
